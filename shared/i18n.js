  function fill(s, vars) {
    if (!vars) return s;
    return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
  }

  /** 取词:en 环境查表,否则返回中文原文;均做 {x} 变量填充 */
  function tr(s, vars) {
    let out = s;
    if (lang === 'en' && Object.prototype.hasOwnProperty.call(EN, s)) out = EN[s];
    return fill(out, vars);
  }

  /** 静态 HTML 汉化:文本节点 + title/placeholder/aria-label 属性各走一遍 */
  function apply(root) {
    if (lang !== 'en') return;
    const r = root || document;
    const walker = document.createTreeWalker(r, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
        const p = node.parentElement;
        if (p && /^(SCRIPT|STYLE)$/.test(p.tagName)) return NodeFilter.FILTER_REJECT;
        return EN[node.nodeValue.trim()] ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
      },
    });
    const hits = [];
    while (walker.nextNode()) hits.push(walker.currentNode);
    for (const node of hits) {
      node.nodeValue = node.nodeValue.replace(node.nodeValue.trim(), EN[node.nodeValue.trim()]);
    }
    for (const el of r.querySelectorAll('[title],[placeholder],[aria-label]')) {
      for (const attr of ['title', 'placeholder', 'aria-label']) {
        const v = el.getAttribute(attr);
        if (v && EN[v]) el.setAttribute(attr, EN[v]);
      }
    }
  }

  root.tr = tr;
  root.BGTI18N = { t: tr, tr, apply, lang, EN };
  if (typeof document !== 'undefined' && document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => apply(document));
  } else if (typeof document !== 'undefined') {
    apply(document);
  }
